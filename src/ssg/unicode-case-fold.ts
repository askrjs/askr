export function foldPortablePathCase(value: string): string {
  return [...value]
    .map((character) => {
      const codePoint = character.codePointAt(0)!;
      if (codePoint >= 0xab70 && codePoint <= 0xabbf) {
        return String.fromCodePoint(codePoint - 0x97d0);
      }
      if (codePoint >= 0x13a0 && codePoint <= 0x13f5) {
        // Cherokee's default case fold uses uppercase as its canonical form.
        return character;
      }
      if (codePoint >= 0x13f8 && codePoint <= 0x13fd) {
        return String.fromCodePoint(codePoint - 0x8);
      }
      return SUPPLEMENTAL_CASE_FOLDS.get(character) ?? character.toLowerCase();
    })
    .join('')
    .normalize('NFC');
}
